#!/usr/bin/env bash
# Wrap-up for the Tier 1 n=50 full run.
#
# Watches outputs/tier1/vbench_opsd/eval_results.json; once it appears
# (meaning the pipeline reached stage 4 for OPSD, the last step), it:
#   1. regenerates all docs/figures/* from the FULL-RUN outputs (not mini)
#   2. picks 3 representative clips per method into docs/figures/final/
#   3. commits + pushes the Markdown table + figures + json
#
# Usage:
#     bash scripts/wrap_up_full_run.sh &
#     # or just run it after the pipeline finishes
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$HERE"
source .venv/bin/activate 2>/dev/null || true

OPSD_EVAL="outputs/tier1/vbench_opsd/eval_results.json"
TABLE_MD="outputs/tier1/tier1_main_table.md"

echo "[wrap-up] polling $OPSD_EVAL ..."
while [[ ! -f "$OPSD_EVAL" ]] || [[ ! -f "$TABLE_MD" ]]; do
  sleep 300
  echo "[wrap-up] $(date '+%H:%M:%S') still waiting"
done
echo "[wrap-up] full-run artifacts detected — proceeding."

# -------------------------------------------------------- 1. figures from full
# Point make_figures.py and diagnose_reward_hacking.py at outputs/tier1 instead
# of outputs/tier1_mini by overriding via env.
export OPSD_I2V_SOURCE="outputs/tier1"
python scripts/make_figures.py || true
python scripts/diagnose_reward_hacking.py || true

# -------------------------------------------------------- 2. pick representatives
mkdir -p docs/figures/final
# For each method, copy 3 clips: 1 best (highest aesthetic opsd gain if applies),
# 1 median, 1 worst. For now just grab prompt indices [0, 10, 25] / seed 0.
for method in base opsd; do
  for idx in 000 010 025; do
    src="outputs/tier1/videos_${method}/seed_00/${idx}.mp4"
    [[ -f "$src" ]] && cp "$src" "docs/figures/final/${method}_${idx}.mp4"
  done
done

# -------------------------------------------------------- 3. commit + push
cd _portfolio_repo/ml-portfolio 2>/dev/null || { cd ../_portfolio_repo/ml-portfolio; }
PORTFOLIO_ROOT=$(pwd)
cd "$HERE"
rsync -a --delete \
  --exclude='.env' --exclude='weights/' --exclude='outputs/' \
  --exclude='third_party/' --exclude='.venv/' --exclude='__pycache__/' \
  --exclude='logs/' --exclude='wandb/' --exclude='.DS_Store' \
  --exclude='data/first_frames/*.png' --exclude='data/vbench_i2v_prompts/*.json' \
  --exclude='scripts/_dl_sd35m.py' \
  ./ "$PORTFOLIO_ROOT/08-video-opsd-i2v/"

# Copy the key outputs explicitly (they live under outputs/ which is .gitignored).
cp outputs/tier1/tier1_main_table.md "$PORTFOLIO_ROOT/08-video-opsd-i2v/docs/figures/final/tier1_main_table.md"
cp outputs/tier1/stats.json          "$PORTFOLIO_ROOT/08-video-opsd-i2v/docs/figures/final/stats.json"
cp outputs/tier1/vbench_base/eval_results.json "$PORTFOLIO_ROOT/08-video-opsd-i2v/docs/figures/final/vbench_base_results.json"
cp outputs/tier1/vbench_opsd/eval_results.json "$PORTFOLIO_ROOT/08-video-opsd-i2v/docs/figures/final/vbench_opsd_results.json"

cd "$PORTFOLIO_ROOT"
git add 08-video-opsd-i2v/
git -c user.email="jingxi@users.noreply.github.com" \
    -c user.name="jingxiduan" \
    commit -m "08: Tier 1 n=50 full-run results — main table + figures + 6 representative clips

Automatically generated by scripts/wrap_up_full_run.sh after the overnight run.
See docs/figures/final/tier1_main_table.md for the Wilcoxon table with
Holm-Bonferroni-adjusted p-values, and docs/figures/final/*.mp4 for the
pick clips (3 per method)." || echo "[wrap-up] nothing new to commit"
git push origin main
echo "[wrap-up] DONE — pushed to GitHub."
