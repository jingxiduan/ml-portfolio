"""Test whether the three industries are statistically separable.

Two questions are kept strictly apart, because they are different claims:

  Q1  separability of the REAL footage
      Given the per-clip motion statistics measured on public video, can an
      industry label be recovered above chance? This is the ceiling: if the real
      footage does not separate, no model trained on those bands can be expected
      to separate either.

  Q2  separability of the TRAINED POLICIES
      Given motion generated by the three OPSD personas on the same held-out
      audio clips, can the persona that produced a clip be identified above
      chance? Clips are paired across variants (identical audio and seed), so
      clip-level variance is removed.

Statistics reported for every pair, and for the three-way problem:
    Mann-Whitney U with the probability of superiority AUC and Cliff's delta
    bootstrap 95 % confidence interval of the median difference
    Kruskal-Wallis H across all three groups
    leave-one-out nearest-centroid classification accuracy, with a permutation
    null and the confusion matrix
    for paired data additionally: Wilcoxon signed-rank, paired Cohen's d, and
    the fraction of clips in which the ordering prescribed by the measured
    bands is reproduced, tested against the 1/6 chance level

Writes outputs/separation_real.json or outputs/separation_model.json.
"""
import argparse
import glob
import json
import os
import sys

import numpy as np
from scipy import stats

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.abspath(os.path.join(ROOT, "src")))

FPS = 25.0
POSE_DIMS = [67, 68, 69]
ORDER = ["realestate", "finance", "shortvideo"]   # ascending measured band
RNG = np.random.default_rng(0)


def band_std(x, lo, hi, fs=FPS):
    from scipy.signal import butter, filtfilt
    x = np.asarray(x, dtype=np.float64)
    if len(x) < 24:
        return 0.0
    ny = fs / 2.0
    b, a = butter(2, [lo / ny, min(hi / ny, 0.99)], btype="band")
    return float(np.std(filtfilt(b, a, x)))


# ---------------------------------------------------------------- statistics
def boot_ci_diff(a, b, n=10000, alpha=0.05):
    """Bootstrap CI for median(a) - median(b)."""
    d = np.empty(n)
    for i in range(n):
        d[i] = np.median(RNG.choice(a, len(a), True)) - np.median(RNG.choice(b, len(b), True))
    return float(np.percentile(d, 100 * alpha / 2)), float(np.percentile(d, 100 * (1 - alpha / 2)))


def pairwise(a, b, na, nb, paired=False):
    r = {"n_a": int(len(a)), "n_b": int(len(b))}
    r["median_a"] = float(np.median(a))
    r["median_b"] = float(np.median(b))
    r["mean_a"] = float(np.mean(a))
    r["mean_b"] = float(np.mean(b))
    r["ratio_median"] = float(np.median(a) / max(np.median(b), 1e-9))
    u, p = stats.mannwhitneyu(a, b, alternative="two-sided")
    auc = float(u / (len(a) * len(b)))
    r["mannwhitney_p"] = float(p)
    r["auc"] = auc
    r["cliffs_delta"] = float(2 * auc - 1)
    lo, hi = boot_ci_diff(a, b)
    r["ci95_median_diff"] = [lo, hi]
    sd = np.sqrt(((len(a) - 1) * np.var(a, ddof=1) + (len(b) - 1) * np.var(b, ddof=1))
                 / max(len(a) + len(b) - 2, 1))
    r["cohens_d"] = float((np.mean(a) - np.mean(b)) / sd) if sd > 0 else 0.0
    if paired and len(a) == len(b):
        d = np.asarray(a) - np.asarray(b)
        try:
            r["wilcoxon_p"] = float(stats.wilcoxon(d).pvalue)
        except ValueError:
            r["wilcoxon_p"] = None
        r["paired_t_p"] = float(stats.ttest_rel(a, b).pvalue)
        r["paired_mean_diff"] = float(np.mean(d))
        r["paired_d"] = float(np.mean(d) / np.std(d, ddof=1)) if np.std(d, ddof=1) > 0 else 0.0
    r["separable"] = bool(p < 0.05 and abs(r["cliffs_delta"]) > 0.5)
    return r


def loo_nearest_centroid(X, y, n_perm=5000):
    """Leave-one-out nearest-centroid accuracy, permutation null, confusion matrix."""
    X = np.asarray(X, dtype=np.float64)
    y = np.asarray(y)
    labels = sorted(set(y.tolist()))
    correct = 0
    conf = {la: {lb: 0 for lb in labels} for la in labels}
    for i in range(len(y)):
        tr = np.ones(len(y), bool)
        tr[i] = False
        cen = {la: X[tr & (y == la)].mean(0) for la in labels}
        pred = min(labels, key=lambda la: np.linalg.norm(X[i] - cen[la]))
        conf[y[i]][pred] += 1
        correct += int(pred == y[i])
    acc = correct / len(y)

    null = np.empty(n_perm)
    for k in range(n_perm):
        perm = RNG.permutation(y)
        c = 0
        for i in range(len(y)):
            tr = np.ones(len(y), bool)
            tr[i] = False
            cen = {la: X[tr & (perm == la)].mean(0) for la in labels}
            c += int(min(labels, key=lambda la: np.linalg.norm(X[i] - cen[la])) == perm[i])
        null[k] = c / len(y)
    p = float((np.sum(null >= acc) + 1) / (n_perm + 1))
    return {"accuracy": float(acc), "chance": 1.0 / len(labels),
            "permutation_p": p, "null_accuracy_mean": float(null.mean()),
            "confusion": conf, "labels": labels}


def analyse(groups, feature="low_std_deg", paired=False, extra=None):
    """groups: {name: np.ndarray}. extra: {name: np.ndarray} second feature."""
    names = [n for n in ORDER if n in groups] + [n for n in groups if n not in ORDER]
    out = {"feature": feature, "n": {n: int(len(groups[n])) for n in names},
           "pairs": {}, "classification": {}}
    for i in range(len(names)):
        for j in range(i + 1, len(names)):
            key = f"{names[j]}_vs_{names[i]}"      # larger index vs smaller band
            a, b = groups[names[j]], groups[names[i]]
            if np.median(a) < np.median(b):
                a, b = b, a
                key = f"{names[i]}_vs_{names[j]}"
            out["pairs"][key] = pairwise(np.asarray(a), np.asarray(b),
                                         names[i], names[j], paired=paired)
    try:
        h, p = stats.kruskal(*[groups[n] for n in names])
        out["kruskal_H"] = float(h)
        out["kruskal_p"] = float(p)
    except ValueError:
        pass

    X = [np.log(np.asarray(groups[n], dtype=np.float64) + 1e-6) for n in names]
    y = np.concatenate([[n] * len(groups[n]) for n in names])
    X1 = np.concatenate(X)[:, None]
    out["classification"]["amp_1d"] = loo_nearest_centroid(X1, y)
    if extra:
        E = {n: np.asarray(extra[n], dtype=np.float64) for n in names}
        mu = np.concatenate([np.log(E[n] + 1e-6) for n in names]).mean()
        sd = np.concatenate([np.log(E[n] + 1e-6) for n in names]).std() + 1e-9
        X2 = np.concatenate([np.log(np.asarray(groups[n]) + 1e-6)[:, None] for n in names], 0)
        X2 = np.concatenate([X2, ((np.concatenate([np.log(E[n] + 1e-6) for n in names]) - mu)
                                  / sd)[:, None]], 1)
        out["classification"]["amp_jitter_2d"] = loo_nearest_centroid(X2, y)
    return out


def ordering_test(groups, order=ORDER):
    """Fraction of clips in which the prescribed ordering holds; binomial vs 1/6."""
    keys = [k for k in order if k in groups]
    m = min(len(groups[k]) for k in keys)
    if m == 0:
        return None
    ok = 0
    for i in range(m):
        vals = [groups[k][i] for k in keys]
        if all(vals[j] < vals[j + 1] for j in range(len(vals) - 1)):
            ok += 1
    p = float(stats.binomtest(ok, m, 1.0 / 6, alternative="greater").pvalue)
    return {"n_clips": int(m), "order": keys, "concordant": int(ok),
            "fraction": ok / m, "chance": 1 / 6, "binomial_p": p}


# ---------------------------------------------------------------- real footage
def run_real(out_path):
    d = json.load(open(os.path.join(ROOT, "outputs", "industry_bands_full.json")))
    ind = d["industries"]
    groups, extra = {}, {}
    for k, v in ind.items():
        pc = v.get("per_clip", [])
        groups[k] = np.array([c["low_std_deg"] for c in pc], float)
        extra[k] = np.array([c["high_std_deg"] for c in pc], float)
    res = {"source": "real public footage, MediaPipe + solvePnP, per clip",
           "bands_hz": d.get("bands_hz"),
           "amplitude": analyse(groups, "low_std_deg", paired=False, extra=extra),
           "jitter": analyse(extra, "high_std_deg", paired=False)}
    res["ordering"] = None
    print("\n=== Q1  are the real industries separable?  ===")
    for k, v in res["amplitude"]["pairs"].items():
        print(f"  {k:<28} AUC={v['auc']:.3f} d={v['cliffs_delta']:+.3f} "
              f"p={v['mannwhitney_p']:.2g}  median {v['median_a']:.3f} vs {v['median_b']:.3f}"
              f"  {'SEPARABLE' if v['separable'] else 'not separable'}")
    cl = res["amplitude"]["classification"]["amp_1d"]
    print(f"  3-way LOO accuracy {cl['accuracy']:.3f} (chance {cl['chance']:.3f}), "
          f"permutation p={cl['permutation_p']:.4g}")
    print(f"  confusion {cl['confusion']}")
    json.dump(res, open(out_path, "w"), indent=1)
    print("[ok] wrote", out_path)


# ---------------------------------------------------------------- trained policies
def run_model(out_path, n_clips, gpu, max_seconds):
    os.environ.setdefault("CUDA_VISIBLE_DEVICES", str(gpu))
    import torch
    from engine import TalkingHeadEngine
    import opsd_train_motion as T

    eng = TalkingHeadEngine(load_renderer=False)
    layers = T.add_lora(eng.mg.denoising_net, 8, 8)
    lo = torch.tensor([float(eng.tpl[f"min_{k}"][0]) for k in ("pitch", "yaw", "roll")])
    hi = torch.tensor([float(eng.tpl[f"max_{k}"][0]) for k in ("pitch", "yaw", "roll")])
    rng = (hi - lo).numpy()

    clips = sorted(glob.glob(os.path.join(ROOT, "data", "audio_public", "eval", "*.wav")))[:n_clips]
    print(f"[model] {len(clips)} held-out clips, speakers disjoint from training")
    variants = [("base", None)] + [(k, os.path.join(ROOT, "outputs", f"opsd_ind_{k}", "lora.pt"))
                                   for k in ("finance", "realestate", "shortvideo")]
    groups, extra = {}, {}
    for name, path in variants:
        if path and not os.path.exists(path):
            print(f"  [skip] {name}: no checkpoint")
            continue
        if path:
            ck = torch.load(path, map_location="cpu")["lora"]
            with torch.no_grad():
                for i, l in enumerate(layers):
                    l.A_t.data.copy_(ck[f"{i}.A_t"].to(l.A_t.device))
                    l.B_t.data.copy_(ck[f"{i}.B_t"].to(l.B_t.device))
            T.set_mode("trainable")
        else:
            T.set_mode("base")
        ls, hs = [], []
        for w in clips:
            au = eng.load_audio(w, max_seconds)
            with torch.no_grad():
                c = eng.gen_motion(au, cfg_scale=2.0, seed=0)
            P = c[:, POSE_DIMS].numpy() * rng
            ls.append(np.mean([band_std(P[:, j], 0.3, 3.0) for j in range(3)]))
            hs.append(np.mean([band_std(P[:, j], 6.0, 12.5) for j in range(3)]))
        groups[name] = np.array(ls)
        extra[name] = np.array(hs)
        print(f"  {name:<12} amp median {np.median(ls):.3f} deg   jitter median {np.median(hs):.4f} deg")

    paired = len({len(v) for v in groups.values()}) == 1
    res = {"source": "OPSD personas, held-out AISHELL-1 eval clips, identical audio and seed",
           "n_clips": len(clips), "paired": bool(paired),
           "per_clip_amp": {k: v.tolist() for k, v in groups.items()},
           "per_clip_jitter": {k: v.tolist() for k, v in extra.items()},
           "amplitude": analyse(groups, "low_std_deg", paired=paired, extra=extra),
           "jitter": analyse(extra, "high_std_deg", paired=paired)}
    res["ordering"] = ordering_test(groups)

    print("\n=== Q2  are the trained personas separable?  ===")
    for k, v in res["amplitude"]["pairs"].items():
        print(f"  {k:<28} AUC={v['auc']:.3f} d={v['cliffs_delta']:+.3f} "
              f"MW p={v['mannwhitney_p']:.2g} "
              f"paired p={v.get('paired_t_p')} "
              f"{'SEPARABLE' if v['separable'] else 'not separable'}")
    for feat in ("amp_1d", "amp_jitter_2d"):
        if feat in res["amplitude"]["classification"]:
            cl = res["amplitude"]["classification"][feat]
            print(f"  3-way LOO [{feat}] accuracy {cl['accuracy']:.3f} "
                  f"(chance {cl['chance']:.3f}) permutation p={cl['permutation_p']:.4g}")
            print(f"    confusion {cl['confusion']}")
    if res["ordering"]:
        o = res["ordering"]
        print(f"  prescribed ordering reproduced in {o['concordant']}/{o['n_clips']} clips "
              f"({o['fraction']:.3f}, chance {o['chance']:.3f}, binomial p={o['binomial_p']:.3g})")
    json.dump(res, open(out_path, "w"), indent=1)
    print("[ok] wrote", out_path)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--kind", choices=["real", "model"], required=True)
    ap.add_argument("--n-clips", type=int, default=40)
    ap.add_argument("--max-seconds", type=float, default=10.0)
    ap.add_argument("--gpu", type=int, default=1)
    ap.add_argument("--out", default=None)
    a = ap.parse_args()
    if a.kind == "real":
        run_real(a.out or os.path.join(ROOT, "outputs", "separation_real.json"))
    else:
        run_model(a.out or os.path.join(ROOT, "outputs", "separation_model.json"),
                  a.n_clips, a.gpu, a.max_seconds)
